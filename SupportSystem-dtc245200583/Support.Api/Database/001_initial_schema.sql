CREATE TABLE IF NOT EXISTS "Tickets" (
    "Id" uuid PRIMARY KEY,
    "TicketNumber" bigint GENERATED ALWAYS AS IDENTITY,
    "RequesterId" uuid NOT NULL,
    "Subject" varchar(200) NOT NULL,
    "Description" text NOT NULL,
    "Category" varchar(80),
    "Priority" varchar(16) NOT NULL DEFAULT 'Normal'
        CHECK ("Priority" IN ('Low', 'Normal', 'High', 'Urgent')),
    "Status" varchar(16) NOT NULL DEFAULT 'New'
        CHECK ("Status" IN ('New', 'Assigned', 'InProgress', 'Resolved')),
    "TeamId" uuid REFERENCES "Teams" ("Id") ON DELETE RESTRICT,
    "AssigneeId" uuid,
    "CreatedAt" timestamptz NOT NULL,
    "UpdatedAt" timestamptz NOT NULL,
    "AssignedAt" timestamptz,
    "ResolvedAt" timestamptz,
    "Version" integer NOT NULL DEFAULT 1
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_Tickets_TicketNumber" ON "Tickets" ("TicketNumber");
CREATE INDEX IF NOT EXISTS "IX_Tickets_RequesterId_CreatedAt"
    ON "Tickets" ("RequesterId", "CreatedAt");
CREATE INDEX IF NOT EXISTS "IX_Tickets_Status_Priority_CreatedAt"
    ON "Tickets" ("Status", "Priority", "CreatedAt");
CREATE INDEX IF NOT EXISTS "IX_Tickets_TeamId_Status"
    ON "Tickets" ("TeamId", "Status");
CREATE INDEX IF NOT EXISTS "IX_Tickets_AssigneeId_Status"
    ON "Tickets" ("AssigneeId", "Status");

CREATE TABLE IF NOT EXISTS "TicketHistory" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TicketId" uuid NOT NULL REFERENCES "Tickets" ("Id") ON DELETE CASCADE,
    "ActorId" uuid,
    "Action" text NOT NULL,
    "FieldName" text,
    "OldValue" text,
    "NewValue" text,
    "Reason" text,
    "OccurredAt" timestamptz NOT NULL,
    "CorrelationId" uuid NOT NULL
);
CREATE INDEX IF NOT EXISTS "IX_TicketHistory_TicketId_OccurredAt"
    ON "TicketHistory" ("TicketId", "OccurredAt");

CREATE TABLE IF NOT EXISTS "TeamMembers" (
    "TeamId" uuid NOT NULL REFERENCES "Teams" ("Id") ON DELETE CASCADE,
    "UserId" uuid NOT NULL,
    "IsActive" boolean NOT NULL DEFAULT true,
    "JoinedAt" timestamptz NOT NULL,
    CONSTRAINT "PK_TeamMembers" PRIMARY KEY ("TeamId", "UserId")
);

CREATE TABLE IF NOT EXISTS "CategoryTeamRules" (
    "Category" varchar(80) PRIMARY KEY,
    "TeamId" uuid NOT NULL REFERENCES "Teams" ("Id") ON DELETE RESTRICT,
    "IsDefault" boolean NOT NULL DEFAULT false,
    "IsActive" boolean NOT NULL DEFAULT true,
    "UpdatedAt" timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS "OutboxMessages" (
    "Id" uuid PRIMARY KEY,
    "Type" text NOT NULL,
    "AggregateId" uuid NOT NULL,
    "Payload" text NOT NULL,
    "OccurredAt" timestamptz NOT NULL,
    "PublishedAt" timestamptz,
    "Attempts" integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS "IX_OutboxMessages_Pending"
    ON "OutboxMessages" ("OccurredAt") WHERE "PublishedAt" IS NULL;

CREATE TABLE IF NOT EXISTS "ProcessedMessages" (
    "ConsumerName" text NOT NULL,
    "MessageId" uuid NOT NULL,
    "ProcessedAt" timestamptz NOT NULL,
    CONSTRAINT "PK_ProcessedMessages" PRIMARY KEY ("ConsumerName", "MessageId")
);
