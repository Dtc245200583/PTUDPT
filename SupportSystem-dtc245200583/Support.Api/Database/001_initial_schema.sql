CREATE TABLE IF NOT EXISTS "Teams" (
    "Id" uuid PRIMARY KEY,
    "Name" varchar(120) NOT NULL,
    "IsActive" boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Teams_Name" ON "Teams" ("Name");

